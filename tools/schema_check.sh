#!/bin/sh
# Check the Rust image's schema files (see apps/api-rs/migrations/README.md):
#   - applying apps/api-rs/migrations/*.sql in order to apps/api-rs/baseline.sql (the schema at the
#     oldest revision portal-api can upgrade) reproduces apps/api-rs/schema.sql, stamp included;
#   - each migration moves alembic_version to its own revision;
#   - every migration file is registered in MIGRATIONS (apps/api-rs/src/migrate.rs).
#
#   tools/schema_check.sh            # check; exit 1 on drift
#   tools/schema_check.sh --write    # regenerate schema.sql from baseline + migrations
#
# Needs only Docker: runs against a throwaway postgres:16 container.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
api="$root/apps/api-rs"
schema="$api/schema.sql"
baseline="$api/baseline.sql"
migrations="$api/migrations"
name="portal-schema-check-$$"

# --- the chain: each migration starts with "-- portal-migration: <from> -> <to>" --------------
steps=$(for f in "$migrations"/*.sql; do
	[ -e "$f" ] || continue
	sed -n '1s/^-- portal-migration: \([0-9a-f]*\) -> \([0-9a-f]*\)$/\1 \2/p' "$f" | grep . ||
		{ echo "$f: first line must be '-- portal-migration: <from> -> <to>'" >&2; echo BAD; }
done)
case "$steps" in *BAD*) exit 1 ;; esac
for to in $(printf '%s\n' "$steps" | cut -d' ' -f2); do
	grep -v '^[[:space:]]*//' "$api/src/migrate.rs" | grep -qF "include_str!(\"../migrations/$to.sql\")" ||
		{ echo "migrations/$to.sql is not registered in MIGRATIONS (src/migrate.rs)" >&2; exit 1; }
done
stamp() { sed -n "s/^INSERT INTO public.alembic_version (version_num) VALUES ('\([0-9a-f]*\)');\$/\1/p" "$1"; }
base=$(stamp "$baseline")
[ -n "$base" ] || { echo "$baseline must end with its alembic_version stamp" >&2; exit 1; }

docker run -d --rm --name "$name" \
	-e POSTGRES_USER=portal -e POSTGRES_PASSWORD=portal -e POSTGRES_DB=portal postgres:16 >/dev/null
generated=$(mktemp)
trap 'rm -f "$generated" "$generated.want" "$generated.got"; docker rm -f "$name" >/dev/null 2>&1 || true' EXIT
until docker exec "$name" pg_isready -U portal -d portal >/dev/null 2>&1; do sleep 0.5; done
# pg_isready answers during the image's init restart; wait for the real server.
until docker exec "$name" psql -U portal -d portal -tAc 'SELECT 1' >/dev/null 2>&1; do sleep 0.5; done

apply() { grep -v '^\\' "$1" | docker exec -i "$name" psql -q -U portal -d portal -v ON_ERROR_STOP=1 >/dev/null; }
revision() { docker exec "$name" psql -U portal -d portal -tAc "SELECT version_num FROM alembic_version" | tr -d '[:space:]'; }

apply "$baseline"
at=$base
walked=0
while to=$(printf '%s\n' "$steps" | awk -v f="$at" '$1 == f { print $2 }') && [ -n "$to" ]; do
	apply "$migrations/$to.sql"
	[ "$(revision)" = "$to" ] ||
		{ echo "migrations/$to.sql must set alembic_version to '$to' (see migrations/README.md)" >&2; exit 1; }
	at=$to
	walked=$((walked + 1))
done
head=$at
total=$(printf '%s\n' "$steps" | grep -c . || true)
[ "$walked" -eq "$total" ] ||
	{ echo "migrations don't form one chain from the baseline ($base): reached $head after $walked of $total" >&2; exit 1; }

{
	docker exec "$name" pg_dump -U portal -d portal --schema-only --no-owner --no-privileges
	cat <<EOF

--
-- Schema revision this file corresponds to. A database created from it is stamped with it;
-- portal-api migrate upgrades older revisions with migrations/ and refuses unknown ones
-- (src/migrate.rs). Generated by tools/schema_check.sh --write; CI fails if it drifts.
--
INSERT INTO public.alembic_version (version_num) VALUES ('$head');
EOF
} >"$generated"

if [ "${1:-}" = "--write" ]; then
	cp "$generated" "$schema"
	echo "wrote $schema (revision $head)"
	exit 0
fi
# Ignore what varies between dumps of the same schema: the \restrict/\unrestrict lines carrying a
# random key, and the server/pg_dump version banner.
stable() { grep -v -e '^\\\(un\)\?restrict ' -e '^-- Dumped \(from database\|by pg_dump\) version ' "$1"; }
stable "$schema" >"$generated.want"
stable "$generated" >"$generated.got"
if diff -u "$generated.want" "$generated.got"; then
	echo "schema.sql matches baseline + migrations ($base -> $head)"
else
	echo "schema.sql has drifted from baseline + migrations ($head) — run: $0 --write" >&2
	exit 1
fi
